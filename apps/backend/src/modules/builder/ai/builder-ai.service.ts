export interface BuilderAiRequest {
  prompt: string;
  pageSlug?: string;
  layout?: Record<string, unknown>;
  selectedId?: string;
  images?: string[];
  code?: string;
  history?: Array<{ role: 'user' | 'assistant'; content: string }>;
}

export interface BuilderAiUsage {
  calls: number;
  inputTokens: number;
  cachedTokens: number;
  outputTokens: number;
}

export interface BuilderAiResult {
  intent: 'edit' | 'build' | 'new_page' | 'answer';
  reply: string;
  /** The current page after the change, for the editor to load as an undoable step. */
  layout?: PageLayout;
  /** Set when the run created a page; the editor opens it. */
  createdPage?: { slug: string; title: string };
  changed: number;
  warnings: string[];
  usage: BuilderAiUsage;
  model: string;
}

export type StepState = 'running' | 'done' | 'error' | 'skipped';
export interface JobStep {
  key: string;
  label: string;
  state: StepState;
  detail?: string;
}

interface Job {
  id: string;
  tenantId: string;
  userId: string;
  status: 'running' | 'done' | 'error';
  steps: JobStep[];
  result?: BuilderAiResult;
  error?: string;
  createdAt: number;
  finishedAt?: number;
}

interface VisionSettings {
  model?: string;
  baseUrl?: string;
  encryptedApiKey?: string;
}

const JOB_TTL_MS = 30 * 60_000;
const RUNS_PER_HOUR = 60;
const SECTION_CONCURRENCY = 4;
const MAX_SECTIONS = 12;
/** Pages bigger than this are sent as an outline plus the selected block, not the whole tree. */
const FULL_TREE_CHARS = 36_000;
const MAX_IMAGE_CHARS = 900_000;
const VISION_PROVIDER = 'builder-vision';

/**
 * The AI page builder.
 *
 * One request runs as a background job so the browser can show progress and no proxy timeout
 * can cut a long build short. A run is:
 *
 *  1. Vision (only with a picture): a vision-capable model turns the screenshot into a precise
 *     written spec. The main model never sees the image, so a text-only model like DeepSeek
 *     still does all the building and the expensive multimodal call happens once.
 *  2. Plan: the main model reads the request and the page and either answers, returns a few
 *     edit operations, or splits a build into self-contained section briefs.
 *  3. Build: each section is generated by its own call, in parallel. Splitting keeps every
 *     reply well inside the output limit and lets one failed section be retried alone.
 *  4. Check: every node is repaired locally where possible and validated with the same
 *     validator that guards publishing; what still fails gets one repair round with the
 *     validator's own messages.
 *
 * Nothing is published. Edits come back to the editor as an undoable change to the draft, and
 * a new page is created as a draft.
 */
@Injectable()
export class BuilderAiService {
  private readonly logger = new Logger(BuilderAiService.name);
  private readonly jobs = new Map<string, Job>();
  private readonly runs = new Map<string, number[]>();

  constructor(
    private readonly drizzle: DrizzleService,
    private readonly provider: AiProviderService,
    private readonly settings: AiSettingsService,
    private readonly secrets: AiSecretService,
    private readonly builder: BuilderService,
  ) {}

  /* ------------------------------------------------------------- jobs */

  start(tenantId: string, actor: Actor, request: BuilderAiRequest): { id: string } {
    this.sweep();
    this.assertRate(tenantId);
    this.assertRequest(request);
    const job: Job = {
      id: randomUUID(),
      tenantId,
      userId: actor.id,
      status: 'running',
      steps: [],
      createdAt: Date.now(),
    };
    this.jobs.set(job.id, job);
    void this.run(job, actor, request)
      .then((result) => {
        job.result = result;
        job.status = 'done';
      })
      .catch((error: unknown) => {
        job.status = 'error';
        job.error = this.describeError(error);
        for (const step of job.steps) if (step.state === 'running') step.state = 'error';
        this.logger.warn(`AI build failed: ${job.error}`);
      })
      .finally(() => {
        job.finishedAt = Date.now();
      });
    return { id: job.id };
  }

  get(tenantId: string, userId: string, id: string) {
    const job = this.jobs.get(id);
    if (!job || job.tenantId !== tenantId) throw new NotFoundException('This AI run has expired');
    if (job.userId !== userId) throw new ForbiddenException();
    return {
      id: job.id,
      status: job.status,
      steps: job.steps,
      result: job.result,
      error: job.error,
      elapsedMs: (job.finishedAt ?? Date.now()) - job.createdAt,
    };
  }

  private sweep() {
    const cutoff = Date.now() - JOB_TTL_MS;
    for (const [id, job] of this.jobs) if (job.createdAt < cutoff) this.jobs.delete(id);
  }

  private assertRate(tenantId: string) {
    const hourAgo = Date.now() - 3_600_000;
    const recent = (this.runs.get(tenantId) ?? []).filter((time) => time > hourAgo);
    if (recent.length >= RUNS_PER_HOUR) {
      throw new HttpException(
        `The AI builder is limited to ${RUNS_PER_HOUR} requests an hour to keep costs predictable. Try again shortly.`,
        HttpStatus.TOO_MANY_REQUESTS,
      );
    }
    recent.push(Date.now());
    this.runs.set(tenantId, recent);
  }

  private assertRequest(request: BuilderAiRequest) {
    for (const image of request.images ?? []) {
      if (!/^data:image\/(png|jpe?g|webp|gif);base64,/i.test(image)) {
        throw new BadRequestException('Pictures must be PNG, JPEG, WebP or GIF');
      }
      if (image.length > MAX_IMAGE_CHARS) throw new BadRequestException('That picture is too large; use one under 650 KB');
    }
  }

  private step(job: Job, key: string, label: string): JobStep {
    const step: JobStep = { key, label, state: 'running' };
    job.steps.push(step);
    return step;
  }

  /* -------------------------------------------------------------- run */

  private async run(job: Job, actor: Actor, request: BuilderAiRequest): Promise<BuilderAiResult> {
    const runtime = await this.settings.getRuntimeConfig(job.tenantId, { requireEnabled: false });
    const usage: BuilderAiUsage = { calls: 0, inputTokens: 0, cachedTokens: 0, outputTokens: 0 };

    const current = request.layout ? this.normalizeLayout(request.layout) : await this.loadLayout(job.tenantId, request.pageSlug);
    const ctx = newBuildContext(current);

    // 1. Vision
    let pictureSpec = '';
    if (request.images?.length) {
      const step = this.step(job, 'vision', 'Reading your picture');
      pictureSpec = await this.describeImages(job.tenantId, runtime, request.images, request.prompt, usage);
      step.state = 'done';
    }

    // 2. Plan
    const planStep = this.step(job, 'plan', 'Planning the change');
    const pages = await this.builder.listPages(job.tenantId).catch(() => [] as Array<{ slug: string; title: string }>);
    const planMessage = this.planMessage(request, current, pages, pictureSpec);
    const plan = await this.askJson(runtime, [{ role: 'user', content: planMessage }], usage, { maxTokens: 6000 });
    const intent = (['edit', 'build', 'new_page', 'answer'] as const).find((value) => value === plan.intent) ?? 'build';
    const reply = typeof plan.reply === 'string' ? plan.reply.slice(0, 1200) : '';
    planStep.state = 'done';

    if (intent === 'answer') {
      return { intent, reply: reply || 'Done.', changed: 0, warnings: [], usage, model: runtime.primaryModel };
    }

    if (intent === 'edit') {
      if (!current) throw new BadRequestException('Open a page first so there is something to edit');
      const step = this.step(job, 'apply', 'Applying the edits');
      const operations = Array.isArray(plan.operations) ? plan.operations.slice(0, 40) : [];
      let applied = applyOperations(current, operations, ctx);
      let issues = layoutIssues(applied.layout);
      if (issues.length || (applied.applied === 0 && applied.errors.length)) {
        step.detail = 'Fixing a few problems';
        const retry = await this.askJson(runtime, [
          { role: 'user', content: planMessage },
          { role: 'assistant', content: JSON.stringify(plan) },
          {
            role: 'user',
            content: `Those operations had problems:\n${[...applied.errors, ...issues].join('\n')}\nReply with the corrected JSON object (same format).`,
          },
        ], usage, { maxTokens: 6000 });
        const retryOps = Array.isArray(retry.operations) ? retry.operations.slice(0, 40) : [];
        const second = applyOperations(current, retryOps, newBuildContext(current));
        const secondIssues = layoutIssues(second.layout);
        if (second.applied > 0 && secondIssues.length === 0) {
          applied = second;
          issues = [];
        }
      }
      if (issues.length) throw new BadRequestException(`The AI's edit did not pass validation: ${issues[0]}`);
      step.state = 'done';
      return {
        intent,
        reply: reply || 'Updated the page.',
        layout: ensureNodeIds(applied.layout),
        changed: applied.applied,
        warnings: [...ctx.warnings, ...applied.errors].slice(0, 12),
        usage,
        model: runtime.primaryModel,
      };
    }

    // 3. Build sections in parallel.
    const briefs = (Array.isArray(plan.sections) ? plan.sections : [])
      .filter((item): item is Record<string, unknown> => !!item && typeof item === 'object')
      .slice(0, MAX_SECTIONS);
    if (briefs.length === 0) throw new BadRequestException('The AI did not plan any sections. Try describing the page in more detail.');
    const style = typeof plan.style === 'string' ? plan.style.slice(0, 1500) : '';
    const buildStep = this.step(job, 'build', `Building ${briefs.length} section${briefs.length === 1 ? '' : 's'}`);
    let finished = 0;
    const source = this.sourceExcerpt(request, pictureSpec);
    const built = await this.mapLimit(briefs, SECTION_CONCURRENCY, async (brief, index) => {
      const node = await this.buildSection(runtime, ctx, current, {
        brief: String(brief.brief ?? '').slice(0, 6000),
        style,
        source,
        position: `${index + 1} of ${briefs.length}`,
        request: request.prompt,
      }, usage).catch((error: unknown) => {
        ctx.warnings.push(`Section ${index + 1} could not be built (${this.describeError(error)}).`);
        return null;
      });
      finished += 1;
      buildStep.detail = `${finished} of ${briefs.length} done`;
      return { node, replaceId: typeof brief.replaceId === 'string' ? brief.replaceId : undefined };
    });
    const nodes = built.filter((item) => item.node);
    if (nodes.length === 0) throw new ServiceUnavailableException('No section could be built. Try again or simplify the request.');
    buildStep.state = 'done';

    // 4. Place
    if (intent === 'new_page') {
      const step = this.step(job, 'page', 'Creating the page');
      const layout = ensureNodeIds({ root: { props: {} }, content: nodes.map((item) => item.node!), schemaVersion: 2 });
      const created = await this.createPage(job.tenantId, actor, plan.page, layout, pages);
      step.state = 'done';
      return {
        intent,
        reply: reply || `Created ${created.title}.`,
        createdPage: created,
        changed: nodes.length,
        warnings: ctx.warnings.slice(0, 12),
        usage,
        model: runtime.primaryModel,
      };
    }

    const base = current ?? { root: { props: {} }, content: [] };
    const layout = this.place(base, nodes as Array<{ node: PuckNode; replaceId?: string }>, String(plan.placement ?? 'append'));
    const issues = layoutIssues(layout);
    if (issues.length) throw new BadRequestException(`The built page did not pass validation: ${issues[0]}`);
    return {
      intent,
      reply: reply || 'Built the sections.',
      layout: ensureNodeIds(layout),
      changed: nodes.length,
      warnings: ctx.warnings.slice(0, 12),
      usage,
      model: runtime.primaryModel,
    };
  }

  /* --------------------------------------------------------- sections */

  private async buildSection(
    runtime: AiProviderRuntimeConfig,
    ctx: BuildContext,
    current: PageLayout | null,
    input: { brief: string; style: string; source: string; position: string; request: string },
    usage: BuilderAiUsage,
  ): Promise<PuckNode> {
    const message = [
      sectionInstructions(),
      `Section ${input.position}.`,
      `Admin's request: ${input.request}`,
      input.style ? `Shared design direction: ${input.style}` : '',
      `Section brief: ${input.brief}`,
      input.source
        ? `Source material (copy its text word for word and its colours exactly; do not invent or rename anything):\n${input.source}`
        : '',
      `Media you may use: ${this.mediaList(current).join(' , ') || 'none'}`,
    ].filter(Boolean).join('\n\n');
    const messages: AiProviderCompletionInput['messages'] = [{ role: 'user', content: message }];

    for (let attempt = 0; attempt < 2; attempt += 1) {
      const reply = await this.askJson(runtime, messages, usage, { maxTokens: 7000 });
      const raw = (reply.node ?? reply) as AiNode;
      const local = { ...ctx, warnings: [] as string[] };
      const node = fromAiNode(raw, local);
      const issues = node ? layoutIssues({ root: { props: {} }, content: [node] }) : ['The reply did not contain a valid block.'];
      if (node && issues.length === 0) {
        ctx.warnings.push(...local.warnings.slice(0, 3));
        return node;
      }
      messages.push(
        { role: 'assistant', content: JSON.stringify(reply).slice(0, 20000) },
        { role: 'user', content: `That block has problems:\n${issues.join('\n')}\nReply with the corrected {"node": ...}.` },
      );
    }
    throw new Error('validation failed twice');
  }

  private place(base: PageLayout, nodes: Array<{ node: PuckNode; replaceId?: string }>, placement: string): PageLayout {
    const content = [...(base.content ?? [])];
    const fresh: PuckNode[] = [];
    for (const item of nodes) {
      const index = item.replaceId ? content.findIndex((node) => node.props?.id === item.replaceId) : -1;
      if (index >= 0) content[index] = item.node;
      else fresh.push(item.node);
    }
    if (fresh.length === 0) return { ...base, content };
    if (placement === 'replace_page') return { ...base, content: fresh };
    if (placement === 'prepend') return { ...base, content: [...fresh, ...content] };
    const match = placement.match(/^(after|before):(.+)$/);
    if (match) {
      const at = content.findIndex((node) => node.props?.id === match[2]);
      if (at >= 0) {
        content.splice(match[1] === 'after' ? at + 1 : at, 0, ...fresh);
        return { ...base, content };
      }
    }
    return { ...base, content: [...content, ...fresh] };
  }

  /* ------------------------------------------------------------ pages */

  private async createPage(
    tenantId: string,
    actor: Actor,
    raw: unknown,
    layout: PageLayout,
    existing: Array<{ slug: string }>,
  ): Promise<{ slug: string; title: string }> {
    const meta = (raw && typeof raw === 'object' ? raw : {}) as Record<string, unknown>;
    const title = (typeof meta.title === 'string' && meta.title.trim() ? meta.title.trim() : 'New page').slice(0, 255);
    const base = (typeof meta.slug === 'string' ? meta.slug : title)
      .toLowerCase()
      .normalize('NFKD')
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 80) || 'new-page';
    const taken = new Set(existing.map((page) => page.slug));
    let slug = base;
    for (let n = 2; taken.has(slug); n += 1) slug = `${base}-${n}`;

    let created: { slug: string; title: string } | undefined;
    for (let attempt = 0; attempt < 3 && !created; attempt += 1) {
      try {
        const page = await this.builder.createPage(tenantId, {
          slug,
          title,
          seoTitle: typeof meta.seoTitle === 'string' ? meta.seoTitle.slice(0, 255) : null,
          seoDescription: typeof meta.seoDescription === 'string' ? meta.seoDescription.slice(0, 500) : null,
        }, actor);
        if (page) created = { slug: page.slug, title: page.title };
      } catch (error) {
        // A reserved or taken slug: try the next free variant.
        if (!(error instanceof BadRequestException)) throw error;
        slug = `${base}-${Math.random().toString(36).slice(2, 6)}`;
      }
    }
    if (!created) throw new BadRequestException('Could not find a free address for the new page');
    await this.builder.savePage(tenantId, created.slug, { layout, title: created.title }, actor);
    return created;
  }

  private async loadLayout(tenantId: string, slug?: string): Promise<PageLayout | null> {
    if (!slug) return null;
    const page = await this.builder.getPage(tenantId, slug).catch(() => null);
    return page ? this.normalizeLayout(page.layout as unknown as Record<string, unknown>) : null;
  }

  private normalizeLayout(raw: Record<string, unknown>): PageLayout {
    const content = Array.isArray(raw.content) ? (raw.content as PuckNode[]) : [];
    const root = raw.root && typeof raw.root === 'object' ? (raw.root as PageLayout['root']) : { props: {} };
    return ensureNodeIds({ root, content, schemaVersion: 2 });
  }

  /* --------------------------------------------------------- messages */

  private planMessage(
    request: BuilderAiRequest,
    current: PageLayout | null,
    pages: Array<{ slug: string; title: string }>,
    pictureSpec: string,
  ): string {
    const parts: string[] = [PLANNER_INSTRUCTIONS];
    parts.push(`Site pages: ${pages.map((page) => `/${page.slug} (${page.title})`).join(', ') || 'none yet'}`);
    parts.push('Built-in routes: /courses, /academies, /products, /events, /certificates/verify, /login, /register');
    if (current && countNodes(current) > 0) {
      const tree = toAiTree(current);
      const full = JSON.stringify(tree);
      if (full.length <= FULL_TREE_CHARS) {
        parts.push(`Current page "${request.pageSlug ?? ''}" (top-level blocks in order):\n${full}`);
      } else {
        parts.push(`Current page "${request.pageSlug ?? ''}" is large; outline with ids:\n${outlineTree(tree).join('\n').slice(0, 24_000)}`);
      }
      if (request.selectedId) {
        const selected = this.findAi(tree, request.selectedId);
        if (selected) parts.push(`Selected block (#${request.selectedId}):\n${JSON.stringify(selected).slice(0, 20_000)}`);
      }
    } else {
      parts.push('The current page is empty.');
    }
    const history = (request.history ?? []).slice(-6);
    if (history.length) {
      parts.push(`Earlier in this conversation:\n${history.map((turn) => `${turn.role}: ${turn.content.slice(0, 1500)}`).join('\n')}`);
    }
    const source = this.sourceExcerpt(request, pictureSpec);
    if (source) parts.push(`Source material to reproduce:\n${source}`);
    parts.push(`Admin's request: ${request.prompt}`);
    return parts.join('\n\n');
  }

  private sourceExcerpt(request: BuilderAiRequest, pictureSpec: string): string {
    const parts: string[] = [];
    if (pictureSpec) parts.push(`Picture description:\n${pictureSpec}`);
    if (request.code?.trim()) parts.push(`Code:\n${this.trimCode(request.code)}`);
    return parts.join('\n\n');
  }

  /** Strips what costs tokens without carrying design: scripts, SVG paths, long data URLs, comments. */
  private trimCode(code: string): string {
    return code
      .replace(/<script[\s\S]*?<\/script>/gi, '')
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/\sd="[^"]{80,}"/g, ' d="…"')
      .replace(/data:[a-z]+\/[a-z0-9.+-]+;base64,[A-Za-z0-9+/=]{100,}/gi, 'data:…')
      .replace(/[ \t]{2,}/g, ' ')
      .replace(/\n{3,}/g, '\n\n')
      .slice(0, 40_000);
  }

  private mediaList(current: PageLayout | null): string[] {
    const urls = new Set<string>();
    if (current) {
      walkLayoutNodes(current, (node) => {
        for (const key of ['src', 'imageUrl', 'bgImage', 'image', 'logo']) {
          const value = node.props?.[key];
          if (typeof value === 'string' && /^https?:\/\//.test(value)) urls.add(value);
        }
      });
    }
    for (const value of Object.values(LANDING_MEDIA)) urls.add(value);
    return [...urls].slice(0, 16);
  }

  private findAi(nodes: AiNode[], id: string): AiNode | null {
    for (const node of nodes) {
      if (node.id === id) return node;
      for (const value of Object.values(node)) {
        if (Array.isArray(value)) {
          const found = this.findAi(value as AiNode[], id);
          if (found) return found;
        }
      }
    }
    return null;
  }

  /* ----------------------------------------------------------- models */

  private async askJson(
    runtime: AiProviderRuntimeConfig,
    messages: AiProviderCompletionInput['messages'],
    usage: BuilderAiUsage,
    options: { maxTokens: number },
  ): Promise<Record<string, unknown>> {
    const call = async (json: boolean, extraNote?: string) => {
      const result = await this.provider.complete({
        baseUrl: runtime.baseUrl,
        apiKey: runtime.apiKey,
        model: runtime.primaryModel,
        fallbackModel: runtime.fallbackModel,
        messages: [
          { role: 'system', content: builderSystemPrompt() },
          ...messages,
          ...(extraNote ? [{ role: 'user' as const, content: extraNote }] : []),
        ],
        maxTokens: options.maxTokens,
        temperature: 0.3,
        timeoutMs: Math.min(Math.max(runtime.timeoutMs, 110_000), 120_000),
        json,
      });
      usage.calls += 1;
      usage.inputTokens += result.inputTokens;
      usage.cachedTokens += result.cachedTokens ?? 0;
      usage.outputTokens += result.outputTokens;
      return result.content;
    };

    let content: string;
    try {
      content = await call(true);
    } catch (error) {
      // Some OpenAI-compatible hosts reject `response_format`; ask again without it.
      if (error instanceof AiProviderError && error.code === 'http_error' && error.providerStatus === 400) {
        content = await call(false);
      } else {
        throw error;
      }
    }
    const parsed = parseJsonObject(content);
    if (parsed) return parsed;
    const again = await call(true, 'Your last reply was not a single valid JSON object. Reply again with only the JSON object.');
    const second = parseJsonObject(again);
    if (second) return second;
    throw new ServiceUnavailableException('The AI replied in a format the builder could not read. Try again.');
  }

  private async describeImages(
    tenantId: string,
    runtime: AiProviderRuntimeConfig,
    images: string[],
    prompt: string,
    usage: BuilderAiUsage,
  ): Promise<string> {
    const vision = await this.visionRuntime(tenantId, runtime);
    const content: AiMessageContent = [
      { type: 'text', text: `${VISION_PROMPT}\n\nThe admin's request, for context: ${prompt}` },
      ...images.slice(0, 3).map((url) => ({ type: 'image_url' as const, image_url: { url } })),
    ];
    try {
      const result = await this.provider.complete({
        baseUrl: vision.baseUrl,
        apiKey: vision.apiKey,
        model: vision.model,
        messages: [{ role: 'user', content }],
        maxTokens: 4000,
        temperature: 0.1,
        timeoutMs: 110_000,
      });
      usage.calls += 1;
      usage.inputTokens += result.inputTokens;
      usage.outputTokens += result.outputTokens;
      return result.content.slice(0, 16_000);
    } catch (error) {
      if (error instanceof AiProviderError && error.code === 'http_error' && (error.providerStatus === 400 || error.providerStatus === 422 || error.providerStatus === 404)) {
        throw new BadRequestException(
          vision.configured
            ? `The vision model "${vision.model}" rejected the picture (${error.providerMessage ?? `HTTP ${error.providerStatus}`}). Check the vision model settings.`
            : `Your AI model "${vision.model}" cannot read pictures. Add a vision model in the AI builder settings, or paste the page's code instead.`,
        );
      }
      throw error;
    }
  }

  private async visionRuntime(tenantId: string, runtime: AiProviderRuntimeConfig) {
    const stored = await this.readVision(tenantId);
    if (!stored.model) {
      return { baseUrl: runtime.baseUrl, apiKey: runtime.apiKey, model: runtime.primaryModel, configured: false };
    }
    let apiKey = runtime.apiKey;
    if (stored.encryptedApiKey) {
      try {
        apiKey = this.secrets.decrypt(stored.encryptedApiKey, tenantId, VISION_PROVIDER);
      } catch {
        throw new ServiceUnavailableException('The saved vision API key could not be read; save it again in the AI builder settings');
      }
    }
    return { baseUrl: stored.baseUrl || runtime.baseUrl, apiKey, model: stored.model, configured: true };
  }

  /* --------------------------------------------------------- settings */

  private async readVision(tenantId: string): Promise<VisionSettings> {
    const row = await this.drizzle.db.query.tenants.findFirst({ where: eq(tenants.id, tenantId) });
    const settings = (row?.settings ?? {}) as Record<string, unknown>;
    const builderAi = (settings.builderAi ?? {}) as Record<string, unknown>;
    return (builderAi.vision ?? {}) as VisionSettings;
  }

  async getSettings(tenantId: string) {
    const vision = await this.readVision(tenantId);
    const runtime = await this.settings.getMaskedSettings(tenantId).catch(() => null);
    return {
      mainModel: runtime?.primaryModel ?? null,
      mainBaseUrl: runtime?.baseUrl ?? null,
      visionModel: vision.model ?? null,
      visionBaseUrl: vision.baseUrl ?? null,
      hasVisionKey: Boolean(vision.encryptedApiKey),
    };
  }

  async saveSettings(
    tenantId: string,
    input: { visionModel?: string | null; visionBaseUrl?: string | null; visionApiKey?: string | null },
  ) {
    const current = await this.readVision(tenantId);
    const next: VisionSettings = { ...current };
    if (input.visionModel !== undefined) next.model = input.visionModel?.trim() || undefined;
    if (input.visionBaseUrl !== undefined) {
      const raw = input.visionBaseUrl?.trim();
      if (raw) {
        try {
          next.baseUrl = await this.provider.assertSafeUrl(raw);
        } catch (error) {
          const code = error instanceof AiProviderError ? error.code : 'invalid_url';
          throw new BadRequestException(
            code === 'host_not_allowed'
              ? 'That host is not on the server\'s AI_PROVIDER_ALLOWED_HOSTS list'
              : 'Enter a valid https:// base URL for the vision provider',
          );
        }
      } else {
        next.baseUrl = undefined;
      }
    }
    if (input.visionApiKey !== undefined) {
      const key = input.visionApiKey?.trim();
      if (key) {
        if (!this.secrets.configured) throw new ServiceUnavailableException('The server has no AI encryption key, so API keys cannot be stored');
        next.encryptedApiKey = this.secrets.encrypt(key, tenantId, VISION_PROVIDER);
      } else {
        next.encryptedApiKey = undefined;
      }
    }
    const row = await this.drizzle.db.query.tenants.findFirst({ where: eq(tenants.id, tenantId) });
    const settings = { ...((row?.settings ?? {}) as Record<string, unknown>) };
    settings.builderAi = { ...((settings.builderAi ?? {}) as Record<string, unknown>), vision: next };
    await this.drizzle.db.update(tenants).set({ settings }).where(eq(tenants.id, tenantId));
    return this.getSettings(tenantId);
  }

  /* ---------------------------------------------------------- helpers */

  private async mapLimit<T, R>(items: T[], limit: number, fn: (item: T, index: number) => Promise<R>): Promise<R[]> {
    const results = new Array<R>(items.length);
    let next = 0;
    const workers = Array.from({ length: Math.min(limit, items.length) }, async () => {
      while (next < items.length) {
        const index = next++;
        results[index] = await fn(items[index]!, index);
      }
    });
    await Promise.all(workers);
    return results;
  }

  private describeError(error: unknown): string {
    if (error instanceof HttpException) {
      const body = error.getResponse();
      if (typeof body === 'string') return body;
      const record = body as { message?: unknown; detail?: unknown; reason?: unknown };
      if (record.reason === 'missing_api_key' || record.reason === 'no_config_row') {
        return 'No AI provider is set up yet. Add one under Settings → AI Assistant.';
      }
      const message = Array.isArray(record.message) ? record.message.join(', ') : record.message;
      return [message, record.detail].filter((part) => typeof part === 'string' && part).join(': ') || error.message;
    }
    if (error instanceof AiProviderError) {
      if (error.code === 'network_error') return 'The AI provider timed out or could not be reached. Try again.';
      if (error.code === 'http_error') {
        return `The AI provider returned an error${error.providerStatus ? ` (HTTP ${error.providerStatus})` : ''}${error.providerMessage ? `: ${error.providerMessage}` : ''}`;
      }
      return `The AI provider failed (${error.code}).`;
    }
    return error instanceof Error ? error.message : 'Something went wrong';
  }
}

/** The first balanced JSON object in a model reply, tolerating fences and surrounding prose. */
export function parseJsonObject(raw: string): Record<string, unknown> | null {
  const text = raw.replace(/^\s*```(?:json)?/i, '').replace(/```\s*$/, '').trim();
  const attempt = (candidate: string) => {
    try {
      const value = JSON.parse(candidate) as unknown;
      return value && typeof value === 'object' && !Array.isArray(value) ? (value as Record<string, unknown>) : null;
    } catch {
      return null;
    }
  };
  const direct = attempt(text);
  if (direct) return direct;
  const start = text.indexOf('{');
  if (start < 0) return null;
  let depth = 0;
  let inString = false;
  let escaped = false;
  for (let i = start; i < text.length; i += 1) {
    const ch = text[i];
    if (inString) {
      if (escaped) escaped = false;
      else if (ch === '\\') escaped = true;
      else if (ch === '"') inString = false;
      continue;
    }
    if (ch === '"') inString = true;
    else if (ch === '{') depth += 1;
    else if (ch === '}') {
      depth -= 1;
      if (depth === 0) return attempt(text.slice(start, i + 1));
    }
  }
  return null;
}
