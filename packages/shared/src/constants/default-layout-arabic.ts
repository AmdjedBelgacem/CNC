/**
 * Translates every field of `layout` whose English text is a built-in string. Anything else —
 * text an admin wrote, text already in Arabic — is left exactly as it is.
 */
export function localizeDefaultLayout(layout: PageLayout): PageLayout {
  const draft = harvestPageLayout(layout);
  const translations: Record<string, string> = {};
  for (const field of draft.harvested) {
    const arabic = DEFAULT_LAYOUT_ARABIC[field.value.trim()];
    if (arabic) translations[field.key] = arabic;
  }
  return Object.keys(translations).length ? applyPageTranslations(draft, translations) : layout;
}

/**
 * The page an Arabic visitor receives: the English structure, the stored Arabic copy merged in,
 * and any built-in text still in English filled from the dictionary. The server, the builder's
 * Arabic preview and the publish-time translator all call this, so they cannot disagree.
 */
export function arabicPageLayout(english: PageLayout, storedArabic?: PageLayout | null): PageLayout {
  return localizeDefaultLayout(storedArabic ? mergeLayoutStructure(english, storedArabic) : english);
}
